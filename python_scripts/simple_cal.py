#!/usr/local/bin/python3

# Standard calculator:

x = int(input("Enter first number: "))
y = int(input("Enter second number : "))

addition  = x + y
subtraction = x - y
multiplication = x * y
division = x / y
modulus = x % y
exponenciation = x ** y

print("Addition of x & y :" ,addition)
print("subtraction of x & y :" ,subtraction)
print("Multiplication of x & y :" ,multiplication)
print("Division of x & y :" ,division)
print("Modulus of x & y :" ,modulus)
print("Exponent of x & y :" ,exponenciation)
 
